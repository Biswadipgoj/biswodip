/**
 * Generates components/ui/TechLogo.tsx from the simple-icons package.
 *
 * Authentic brand marks are inlined at build time so the site makes no runtime
 * requests and ships no icon font. Brand logos remain the property of their
 * respective owners and are used here only to identify the technologies used.
 *
 * Run: node scripts/sync-tech-logos.mjs
 */
import fs from 'node:fs';
import * as simpleIcons from 'simple-icons';

/** craft name in lib/data.ts -> simple-icons slug (or a local fallback key) */
const MAP = {
  "TypeScript": "typescript",
  "JavaScript": "javascript",
  "Python": "python",
  "React": "react",
  "Next.js": "nextdotjs",
  "Node.js": "nodedotjs",
  "PostgreSQL": "postgresql",
  "MongoDB": "mongodb",
  "Git": "git",
  "GitHub": "github",
  "HTML": "html5",
  "CSS": "css",
  "Tailwind CSS": "tailwindcss",
  "Material UI": "mui",
  "Vite": "vite",
  "Electron": "electron",
  "Capacitor": "capacitor",
  "Postman": "postman",
  "Vercel": "vercel",
  "Docker": "docker",
  "FastAPI": "fastapi",
  "LangChain": "langchain",
  "Prisma": "prisma",
  "Supabase": "supabase"
};

/** Extra marks used by the hero, stack ribbon and project chips. */
const EXTRA = [];

function lookup(slug) {
  const key = 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);
  return simpleIcons[key];
}

const logos = {};
const missing = [];

for (const [craft, slug] of Object.entries(MAP)) {
  const icon = lookup(slug);
  if (!icon) {
    missing.push(`${craft} -> ${slug}`);
    continue;
  }
  logos[slug] = { t: icon.title, h: icon.hex, p: icon.path };
}

for (const slug of EXTRA) {
  const icon = lookup(slug);
  if (!icon) {
    missing.push(`extra -> ${slug}`);
    continue;
  }
  logos[slug] = { t: icon.title, h: icon.hex, p: icon.path };
}

if (missing.length) {
  console.error('Unresolved simple-icons slugs:\n  ' + missing.join('\n  '));
  process.exit(1);
}

const craftEntries = Object.entries(MAP)
  .map(([craft, slug]) => `  ${JSON.stringify(craft)}: ${JSON.stringify(slug)},`)
  .join('\n');

const logoEntries = Object.entries(logos)
  .map(([slug, data]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(data)},`)
  .join('\n');

const file = `/**
 * AUTO-GENERATED by scripts/sync-tech-logos.mjs — do not edit by hand.
 *
 * Brand marks from simple-icons (CC0-1.0 icon set). Each logo is inlined so the
 * site performs no runtime icon requests. Brand logos are the property of their
 * respective owners and identify the technologies used.
 */

type Logo = { t: string; h: string; p: string };

const LOGOS: Record<string, Logo> = {
${logoEntries}
};

/** Craft name (lib/data.ts) -> logo slug. */
export const CRAFT_LOGOS: Record<string, string> = {
${craftEntries}
};

export type LogoSlug = keyof typeof LOGOS;

export function logoFor(craft: string): Logo | undefined {
  const slug = CRAFT_LOGOS[craft];
  return slug ? LOGOS[slug] : undefined;
}

export function logoBySlug(slug: string): Logo | undefined {
  return LOGOS[slug];
}

/**
 * Renders an authentic brand mark.
 * \`tone\` keeps the official brand colour; \`mono\` inherits currentColor.
 */
export default function TechLogo({
  craft,
  slug,
  size = 26,
  mono = false,
  className = '',
}: {
  craft?: string;
  slug?: string;
  size?: number;
  mono?: boolean;
  className?: string;
}) {
  const logo = craft ? logoFor(craft) : slug ? logoBySlug(slug) : undefined;
  if (!logo) return null;
  return (
    <svg
      className={'tech-logo ' + className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={mono ? 'currentColor' : '#' + logo.h}
      role="img"
      aria-label={logo.t}
      focusable="false"
    >
      <path d={logo.p} />
    </svg>
  );
}
`;

fs.writeFileSync('components/ui/TechLogo.tsx', file);
console.log(`Wrote components/ui/TechLogo.tsx with ${Object.keys(logos).length} brand marks.`);
